-- ============================================================
-- V4__add_project.sql
-- 项目（工作区）隔离：资料与对话归属到项目，RAG 只在当前项目内检索。
-- 兼容策略：老数据全部归入该用户的「默认项目」，迁移后可无感继续使用。
-- 执行顺序：建表 → 补默认项目 → 加列 → 回填 → NOT NULL → FK → 索引
-- ============================================================

CREATE TABLE IF NOT EXISTS project (
    id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description TEXT,
    is_default  BOOLEAN NOT NULL DEFAULT FALSE,
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_project_user FOREIGN KEY (user_id) REFERENCES "user" (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_project_user ON project (user_id);
-- 每个用户至多一个默认项目（并发创建时由数据库兜底，避免出现两个默认项目）
CREATE UNIQUE INDEX IF NOT EXISTS uq_project_user_default ON project (user_id) WHERE is_default;

-- 为已存在的每个用户补一个默认项目（含只有历史数据的账号）
INSERT INTO project (user_id, name, description, is_default)
SELECT u.id, '默认项目', '未归类的资料与对话', TRUE
FROM "user" u
WHERE NOT EXISTS (
    SELECT 1 FROM project p WHERE p.user_id = u.id AND p.is_default
);

-- 归属列：先加可空列，回填后再收紧为 NOT NULL
ALTER TABLE document ADD COLUMN IF NOT EXISTS project_id BIGINT;
ALTER TABLE chat_session ADD COLUMN IF NOT EXISTS project_id BIGINT;

UPDATE document d
SET project_id = (
    SELECT p.id FROM project p
    WHERE p.user_id = d.user_id AND p.is_default
    ORDER BY p.id
    LIMIT 1
)
WHERE d.project_id IS NULL;

UPDATE chat_session s
SET project_id = (
    SELECT p.id FROM project p
    WHERE p.user_id = s.user_id AND p.is_default
    ORDER BY p.id
    LIMIT 1
)
WHERE s.project_id IS NULL;

ALTER TABLE document ALTER COLUMN project_id SET NOT NULL;
ALTER TABLE chat_session ALTER COLUMN project_id SET NOT NULL;

-- 外键用 DO 块判断，保证脚本可重复执行（开发库 flyway 关闭，需要手工跑一次）
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_doc_project') THEN
        ALTER TABLE document
            ADD CONSTRAINT fk_doc_project FOREIGN KEY (project_id) REFERENCES project (id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_session_project') THEN
        ALTER TABLE chat_session
            ADD CONSTRAINT fk_session_project FOREIGN KEY (project_id) REFERENCES project (id) ON DELETE CASCADE;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_document_user_project ON document (user_id, project_id);
CREATE INDEX IF NOT EXISTS idx_chat_session_user_project ON chat_session (user_id, project_id);

-- 向量表增加项目归属：RAG 检索在 SQL 层直接按项目过滤，避免“跨项目串资料”。
-- 聊天附件（source_type=attachment）没有项目语义，保持为空即可。
ALTER TABLE vector_record ADD COLUMN IF NOT EXISTS project_id BIGINT;

UPDATE vector_record vr
SET project_id = d.project_id
FROM document d
WHERE vr.document_id = d.id
  AND vr.source_type = 'knowledge'
  AND vr.project_id IS NULL;

CREATE INDEX IF NOT EXISTS idx_vector_record_user_project
    ON vector_record (user_id, project_id, source_type);
