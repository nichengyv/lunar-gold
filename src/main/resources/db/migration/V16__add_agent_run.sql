-- V16__add_agent_run.sql
--
-- 目的：Phase 4 第一批骨架——运行状态机 + 事件流 + 幂等键
-- 说明：
--   1) 状态流转只在应用层 AgentRunService 中控制，DB 层只存储；
--      任何非法迁移在 Service 层拒绝并写 FAILED，不抛 DB 错误。
--   2) client_request_id 唯一约束保证幂等；NULL 允许（未走幂等入口），
--      PG 的 UNIQUE 不强制多个 NULL 冲突。
--   3) agent_run_event 的 seq 是运行内单调递增事件序号，用于断线续传重放。
--   4) 外键 ON DELETE CASCADE：删 run 时事件一起清，避免孤儿数据。
--   5) 本迁移只建结构，不插入数据，不修改 V1~V15。
-- ============================================================

CREATE TABLE IF NOT EXISTS agent_run (
    id                BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT        NOT NULL,
    session_id        BIGINT,
    project_id        BIGINT,
    client_request_id VARCHAR(128),
    state             VARCHAR(20)   NOT NULL,
    request_json      TEXT,
    result_json       TEXT,
    error_code        VARCHAR(40),
    error_message     TEXT,
    start_time        TIMESTAMP,
    end_time          TIMESTAMP,
    create_time       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    update_time       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_agent_run_client_request
    ON agent_run (user_id, client_request_id)
    WHERE client_request_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_agent_run_user_state
    ON agent_run (user_id, state);

CREATE INDEX IF NOT EXISTS idx_agent_run_session
    ON agent_run (session_id);

CREATE INDEX IF NOT EXISTS idx_agent_run_create
    ON agent_run (create_time);


CREATE TABLE IF NOT EXISTS agent_run_event (
    id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    run_id      BIGINT        NOT NULL REFERENCES agent_run(id) ON DELETE CASCADE,
    seq         INT           NOT NULL,
    event_type  VARCHAR(40)   NOT NULL,
    payload     TEXT,
    create_time TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UNIQUE (run_id, seq)
);

CREATE INDEX IF NOT EXISTS idx_agent_run_event_run_seq
    ON agent_run_event (run_id, seq);
