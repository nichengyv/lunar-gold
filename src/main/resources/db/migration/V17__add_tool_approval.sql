-- Phase 4：审批决策与会话级「总是允许」持久化，桌面重启后可恢复待审批。
CREATE TABLE IF NOT EXISTS tool_approval (
    id               BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    approval_id      VARCHAR(32)  NOT NULL UNIQUE,
    user_id          BIGINT       NOT NULL,
    session_id       BIGINT,
    tool_name        VARCHAR(100) NOT NULL,
    arguments        TEXT,
    risk             VARCHAR(20)  NOT NULL,
    state            VARCHAR(20)  NOT NULL,
    expires_at       BIGINT       NOT NULL,
    remember_session BOOLEAN      NOT NULL DEFAULT FALSE,
    decision_time    TIMESTAMP,
    create_time      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    update_time      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_tool_approval_state ON tool_approval (state);
CREATE INDEX IF NOT EXISTS idx_tool_approval_session_decision
    ON tool_approval (session_id, state, remember_session);
