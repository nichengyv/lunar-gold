-- ============================================================
-- V2__add_knowledge_base.sql（PostgreSQL 方言，A6 修复）
-- 知识库文档、分块、聊天附件表
-- 方言要点：LONGTEXT → TEXT；去掉 ENGINE=InnoDB / CHARSET；
--          索引改用独立的 CREATE INDEX 语句（PG 无表内 INDEX 语法）
-- ============================================================

CREATE TABLE IF NOT EXISTS document (
    id           BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT NOT NULL,
    file_name    VARCHAR(255) NOT NULL,
    file_type    VARCHAR(50) NOT NULL,
    file_size    BIGINT NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    status       VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    description  TEXT,
    chunk_count  INT DEFAULT 0,
    create_time  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_time  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_doc_user FOREIGN KEY (user_id) REFERENCES "user" (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_document_user ON document (user_id);
CREATE INDEX IF NOT EXISTS idx_document_status ON document (status);

CREATE TABLE IF NOT EXISTS document_chunk (
    id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    chunk_index INT NOT NULL,
    content     TEXT NOT NULL,
    token_count INT NOT NULL DEFAULT 0,
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chunk_doc FOREIGN KEY (document_id) REFERENCES document (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_chunk_doc ON document_chunk (document_id);
CREATE INDEX IF NOT EXISTS idx_chunk_user_doc ON document_chunk (user_id, document_id);

CREATE TABLE IF NOT EXISTS chat_attachment (
    id           BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT NOT NULL,
    message_id   BIGINT,
    file_name    VARCHAR(255) NOT NULL,
    file_type    VARCHAR(50) NOT NULL,
    file_size    BIGINT NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    content_text TEXT,
    description  VARCHAR(500),
    create_time  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_chat_att_msg ON chat_attachment (message_id);
CREATE INDEX IF NOT EXISTS idx_chat_att_user ON chat_attachment (user_id);
