-- ============================================================
-- V20__add_api_client.sql
--
-- 目的：P6-01 本地 API 契约与客户端身份。
-- 说明：
--   1) 客户端令牌形如 lgc_<client_id>_<secret>，库内只存 secret 的 SHA-256
--      十六进制（64 字符），明文仅在创建响应里返回一次。
--   2) revoked_at 非空即失效，撤销后下一次请求立即 401，不做内存缓存。
--   3) last_used_at 只在认证成功时更新，便于排查长期不用的客户端。
--   4) 本迁移只建结构，不插入数据，不修改 V1~V19。
-- ============================================================

CREATE TABLE IF NOT EXISTS api_client (
    id           BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    client_id    VARCHAR(32)  NOT NULL,
    user_id      BIGINT       NOT NULL,
    name         VARCHAR(64)  NOT NULL,
    secret_hash  VARCHAR(64)  NOT NULL,
    scopes       VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    revoked_at   TIMESTAMP,
    last_used_at TIMESTAMP,
    CONSTRAINT uk_api_client_client_id UNIQUE (client_id)
);

CREATE INDEX IF NOT EXISTS idx_api_client_user
    ON api_client (user_id);
